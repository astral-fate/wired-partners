"""Provider-matched check of the Study 4 contrasts that use the added arms.

    python scripts/provider_check.py

For GPT-4.1-mini, Gemma-3-12B and GPT-OSS-120B the added Study 4 arms (two rewordings, safe harbour on the
collusive offer, vouching) were served by Experiential Labs, while the base arms were served by OpenRouter. The base
arms they are compared with were rerun on Experiential Labs (results/main_v4_xpl, same seed and trial contexts), and
each contrast is recomputed with both arms from the same provider. Writes paper/numbers_provider.tex (\\N{prov/...}).
"""
import json
import random
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = ["gpt-4.1-mini", "gemma-3-12b", "gpt-oss-120b-or"]
TAG = {"gpt-4.1-mini": "mini", "gemma-3-12b": "gemma", "gpt-oss-120b-or": "oss"}
CONTRASTS = {  # id: (added arm, base arm)
    "p1": ("c_prohibit_p1", "c_reportfree"), "p2": ("c_prohibit_p2", "c_reportfree"),
    "p1_vs_base": ("c_prohibit_p1", "c_prohibit"), "p2_vs_base": ("c_prohibit_p2", "c_prohibit"),
    "safeharbour": ("c_safeharbour_sting50", "c_severe_sting50"),
    "auth_mild": ("c_auth_mild_sting50", "c_mild_sting50"), "auth_severe": ("c_auth_severe_sting50", "c_severe_sting50"),
}


def load(path, served_filter):
    acc = defaultdict(dict)  # (model, condition) -> {trial: accepted}
    for line in (ROOT / path).read_text(encoding="utf-8").splitlines():
        r = json.loads(line)
        if r["model"] in MODELS and served_filter(r.get("served_model") or ""):
            acc[(r["model"], r["condition"])][r["trial"]] = int(r["decision"] == "ACCEPT")
    return acc


main = load("results/main_v4/trials.jsonl", lambda s: True)
xpl_base = load("results/main_v4_xpl/trials.jsonl", lambda s: True)
# OpenRouter-served base arms (identifier carries the vendor prefix) and the Experiential Labs-served added arms
or_base = {k: v for k, v in load("results/main_v4/trials.jsonl", lambda s: "/" in s).items()}


def est(added, base, a, b, reps=5000, seed=3):
    diffs = {m: [added[(m, a)][t] - base[(m, b)][t] for t in sorted(set(added.get((m, a), {})) & set(base.get((m, b), {})))]
             for m in MODELS}
    diffs = {m: d for m, d in diffs.items() if d}
    e = sum(sum(d) / len(d) for d in diffs.values()) / len(diffs)
    rng, draws = random.Random(seed), []
    for _ in range(reps):
        draws.append(sum(sum(rng.choice(d) for _ in d) / len(d) for d in diffs.values()) / len(diffs))
    draws.sort()
    return e, draws[int(.025 * reps)], draws[int(.975 * reps)], {m: sum(d) / len(d) for m, d in diffs.items()}


M, res = {}, {}
for cid, (a, b) in CONTRASTS.items():
    for tag, base in (("matched", xpl_base), ("mixed", or_base)):
        e, lo, hi, per = est(main, base, a, b)
        res[f"{cid}/{tag}"] = {"est": e, "lo": lo, "hi": hi, "per_model": per}
        f = (lambda x: f"{100 * x:+.1f}".replace("-", "$-$"))
        M[f"prov/{cid}/{tag}"], M[f"prov/{cid}/{tag}/lo"], M[f"prov/{cid}/{tag}/hi"] = f(e), f(lo), f(hi)
        for m, v in per.items():
            M[f"prov/{cid}/{tag}/{TAG[m]}"] = f(v)
for m in MODELS:  # base acceptance on each provider
    for cond in ("c_reportfree", "c_prohibit"):
        for tag, base in (("xpl", xpl_base), ("or", or_base)):
            d = base.get((m, cond), {})
            if d:
                M[f"prov/rate/{TAG[m]}/{cond}/{tag}"] = f"{100 * sum(d.values()) / len(d):.0f}"
(ROOT / "results" / "analysis" / "provider_check.json").write_text(json.dumps(res, indent=1), encoding="utf-8")
lines = ["% Generated by scripts/provider_check.py. Do not edit by hand.", r"\makeatletter"]
lines += [rf"\expandafter\def\csname wp@{k}\endcsname{{{v}}}" for k, v in sorted(M.items())]
(ROOT / "paper" / "numbers_provider.tex").write_text("\n".join(lines + [r"\makeatother"]) + "\n", encoding="utf-8")
for k, v in res.items():
    print(f"{k:24s} {100 * v['est']:+6.1f} [{100 * v['lo']:+6.1f}, {100 * v['hi']:+6.1f}]",
          {TAG[m]: round(100 * x) for m, x in v["per_model"].items()})
